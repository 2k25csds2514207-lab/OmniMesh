import { NeutralMessage } from "../context/types";
import { ProviderAdapter, StreamChunk } from "./types";
import { estimateTokens } from "../context/tokens";

export class MockAdapter implements ProviderAdapter {
  id = "mock" as const;
  name = "OmniMesh Mock Simulator";

  toProviderMessages(history: NeutralMessage[]): NeutralMessage[] {
    return history;
  }

  async *stream(params: {
    apiKey: string;
    model: string;
    history: NeutralMessage[];
    signal?: AbortSignal;
  }): AsyncIterable<StreamChunk> {
    const lastUserMsg = [...params.history].reverse().find((m) => m.role === "user");
    const rawPrompt = (lastUserMsg?.content || "Explain how OmniMesh works").trim();
    const displayPrompt =
      rawPrompt.length > 200 ? rawPrompt.slice(0, 197) + "..." : rawPrompt;

    const modelLower = (params.model || "").toLowerCase();
    const isGroq =
      modelLower.includes("groq") ||
      modelLower.includes("oss") ||
      modelLower.includes("allam") ||
      modelLower.includes("llama");
    const isClaude =
      modelLower.includes("claude") ||
      modelLower.includes("sonnet") ||
      modelLower.includes("haiku");
    const isGemini =
      modelLower.includes("gemini") || modelLower.includes("flash");
    const isGpt = !isGroq && !isClaude && !isGemini;

    let responseText = "";
    let initialDelayMs = 120;
    let wordDelayMs = 16;

    const BANNER = `> ⚠️ **Demo / Simulated Sandbox Response**\n> *Generated by OmniMesh Sandbox Runtime. A live API key is required for real-time model completions.*\n\n`;

    if (isGroq) {
      initialDelayMs = 30;
      wordDelayMs = 6;
      responseText =
        BANNER +
        `You asked: **"${displayPrompt}"**\n\n` +
        `---\n\n` +
        `### ⚡ Groq LPU — Ultra-Fast Stream (~500 T/s)\n\n` +
        `This is a simulated sandbox output running on OmniMesh's local evaluation adapter because no live Groq API key is configured.\n\n` +
        `- **Prompt Evaluated**: *"${displayPrompt}"*\n` +
        `- **Engine**: Groq Language Processing Unit (LPU) ultra-low latency architecture.\n` +
        `- **Simulated Speed**: ~480 tokens/sec with sub-50ms initial latency profile.\n` +
        `- **Ideal For**: Real-time agentic workflows, conversational voice loops, and rapid reasoning tasks.\n\n` +
        `*Tip: Groq Cloud offers **100% free API keys** with zero credit card required at [console.groq.com](https://console.groq.com/keys). Add your key in the Vault for genuine live inference.*`;
    } else if (isClaude) {
      initialDelayMs = 160;
      wordDelayMs = 24;
      responseText =
        BANNER +
        `You asked: **"${displayPrompt}"**\n\n` +
        `---\n\n` +
        `### Claude 3.5 Sonnet — Simulated Preview\n\n` +
        `I have examined your inquiry regarding **"${displayPrompt}"** from an architectural perspective.\n\n` +
        `Because OmniMesh is currently running in **Sandbox Mode**, this is an illustrative preview showing Claude 3.5 Sonnet's analytical style and nuance:\n\n` +
        `- **Conceptual Nuance**:\n` +
        `  Addressing *"${displayPrompt}"* requires not only direct execution, but thoughtful attention to boundaries, failure recovery, and interface cleanliness.\n` +
        `- **Architectural Principles**:\n` +
        `  • Separate core domain logic from transport and presentation concerns.\n` +
        `  • Implement explicit defensive checks for malformed or edge-case inputs.\n` +
        `  • Maintain self-documenting type boundaries and readable error semantics.\n` +
        `- **Production Delivery**:\n` +
        `  Once connected to a live Anthropic API key, Claude will generate the comprehensive production-ready implementation accompanied by deep reasoning.\n\n` +
        `*Add your Anthropic API key (\`sk-ant-...\`) in the Key Vault to experience authentic Claude 3.5 Sonnet intelligence.*`;
    } else if (isGemini) {
      initialDelayMs = 140;
      wordDelayMs = 20;
      responseText =
        BANNER +
        `You asked: **"${displayPrompt}"**\n\n` +
        `---\n\n` +
        `### Google Gemini 1.5 Pro — Simulated Preview\n\n` +
        `This is a simulated sandbox response running on OmniMesh's local evaluation adapter. Gemini 1.5 Pro's signature capability is massive context ingestion and multimodal synthesis.\n\n` +
        `**Context Synthesis Matrix for:** *"${displayPrompt}"*\n\n` +
        `| Dimension | Analysis for Your Query | Live Gemini 1.5 Pro Capability |\n` +
        `| :--- | :--- | :--- |\n` +
        `| **Core Query** | *"${displayPrompt.length > 45 ? displayPrompt.slice(0, 42) + "..." : displayPrompt}"* | Rapid factual extraction |\n` +
        `| **Context Scope** | Extended context buffer | Ingests up to 2,000,000 tokens without loss |\n` +
        `| **Data Structure** | Multi-angle matrix synthesis | Rich tabular, multimodal & code parsing |\n\n` +
        `*Tip: Google AI Studio provides **100% free API keys** (no credit card required) at [aistudio.google.com](https://aistudio.google.com/app/apikey). Add your key to activate live Gemini Pro.*`;
    } else {
      // GPT-4o / OpenAI Flagship
      initialDelayMs = 110;
      wordDelayMs = 16;
      responseText =
        BANNER +
        `You asked: **"${displayPrompt}"**\n\n` +
        `---\n\n` +
        `### OpenAI GPT-4o — Simulated Preview\n\n` +
        `This is a simulated sandbox response running on OmniMesh's local evaluation adapter. A live OpenAI API key is needed to execute live GPT-4o reasoning.\n\n` +
        `**Simulated Pragmatic Breakdown for:** *"${displayPrompt}"*\n\n` +
        `1. **Intent Analysis**:\n` +
        `   - Query classified as direct analytical / task-oriented instruction.\n` +
        `   - Requires balanced decomposition and clear functional steps.\n\n` +
        `2. **Actionable Roadmap**:\n` +
        `   - Establish baseline constraints and input requirements.\n` +
        `   - Implement solution modules with deterministic verification.\n` +
        `   - Validate edge conditions and resource utilization.\n\n` +
        `*Add your OpenAI key (\`sk-proj-...\`) in the Encrypted Key Vault to unlock live GPT-4o intelligence and tool calling.*`;
    }

    // Initial model latency simulation
    if (initialDelayMs > 0) {
      await new Promise((resolve) => setTimeout(resolve, initialDelayMs));
    }

    // Stream out words with realistic delays
    const words = responseText.split(" ");
    let accumulated = "";

    for (let i = 0; i < words.length; i++) {
      if (params.signal?.aborted) {
        return;
      }
      const chunk = (i === 0 ? "" : " ") + words[i];
      accumulated += chunk;

      if (wordDelayMs > 0) {
        await new Promise((resolve) => setTimeout(resolve, wordDelayMs));
      }

      yield {
        text: chunk,
        done: false,
      };
    }

    const promptTokens = estimateTokens(rawPrompt);
    const completionTokens = estimateTokens(accumulated);

    yield {
      text: "",
      done: true,
      tokens: {
        prompt: promptTokens,
        completion: completionTokens,
      },
    };
  }
}

